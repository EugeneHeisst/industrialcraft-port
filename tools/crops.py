# Use original crop planes, one model for each age; multipart sticks stay visible with any crop.
stages={}
for tex in sorted(os.listdir(os.path.join(OTEX,'blocks/crop'))):
    m=re.fullmatch(r'(.+)\.(\d)\.png',tex)
    if not m or m[1] == "infested":continue
    plant,stage=m[1].lower(),int(m[2])
    stages.setdefault(plant,[]).append(stage)
    copy(os.path.join(OTEX,'blocks/crop',tex),os.path.join(A,'textures/block/crop',plant+'.'+str(stage)+'.png'))
    write(os.path.join(A,'models/block/crop',plant+'.'+str(stage)+'.json'),{'parent':'minecraft:block/cross','render_type':'minecraft:cutout','textures':{'cross':'ic2:block/crop/'+plant+'.'+str(stage)}})
for plant,ages in stages.items():
    for stage in range(1,8):
        age=max(a for a in ages if a<=min(stage,max(ages)))
        parts.append({'when':{'plant':plant,'size':str(stage)},'apply':{'model':'ic2:block/crop/'+plant+'.'+str(age)}})
write(os.path.join(A,'blockstates/crop.json'),{'multipart':parts})
write(os.path.join(A,'models/item/crop.json'),{'parent':'ic2:block/crop/stick'})
