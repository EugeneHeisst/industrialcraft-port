parts=[]
for stick in ['stick','stick.upgraded']:
    copy(os.path.join(OTEX,'blocks/crop',stick+'.png'),os.path.join(A,'textures/block/crop',stick+'.png'))
    write(os.path.join(A,'models/block/crop',stick+'.json'),{'parent':'minecraft:block/cross','render_type':'minecraft:cutout','textures':{'cross':'ic2:block/crop/'+stick}})
